using Shared.Voxels;

namespace Api;

/// <summary>
/// Ломание удержанием ЛКМ. Время считает сервер по твёрдости блока и инструменту в руке (<see cref="Shared.Items.Mining"/>);
/// когда оно прошло, блок ломается через <see cref="IWorld.TryBreakBlock"/>, а добыча, если она положена, уходит
/// в инвентарь игрока. Ломание отменяется, если игрок отпустил кнопку, сменил предмет, отошёл или блок изменился.
/// </summary>
public interface IBlockBreaker
{
    /// <summary>
    /// Начинает ломать блок от имени игрока (предыдущее ломание отменяется). В творческом режиме и у блока с нулевой
    /// твёрдостью блок ломается сразу.
    /// </summary>
    void StartBreaking(BlockPos pos);
}
