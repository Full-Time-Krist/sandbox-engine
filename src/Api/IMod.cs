namespace Api;

/// <summary>
/// Точка входа мода. Игра создаёт по экземпляру на мод и вызывает <see cref="Load"/> один раз при запуске сервера,
/// после загрузки контента и до первого тика. Ванильный мод <c>base</c> подключается так же.
/// </summary>
public interface IMod
{
    /// <summary>Регистрирует поведения и подписки мода. Регистрировать можно только здесь: после загрузки реестры заморожены.</summary>
    void Load(IModContext context);
}
