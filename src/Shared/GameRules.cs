namespace Shared;

/// <summary>Игровые константы, общие для клиента и сервера: сервер проверяет действия по тем же числам.</summary>
public static class GameRules
{
    /// <summary>Дальность, на которой игрок может выбрать, сломать или поставить блок, в блоках.</summary>
    public const float BlockReach = 6f;

    /// <summary>
    /// Дальность, на которой игрок достаёт до сущности (моба), в блоках — от глаза до короба тела. Меньше, чем до блока:
    /// бой вблизи (раздел 17 DESIGN.md). С шага 9.2 по ней выделяется моб под прицелом, с 9.4 — удар.
    /// </summary>
    public const float EntityReach = 3f;
}
