namespace Shared.Items;

/// <summary>
/// Какое действие игрок применил к предмету в руке. Что оно значит, решает поведение предмета на сервере:
/// для блока основное — сломать, дополнительное — поставить; для еды дополнительное — съесть и т. д.
/// </summary>
public enum ItemAction
{
    /// <summary>Основное действие (по умолчанию ЛКМ).</summary>
    Primary,

    /// <summary>Дополнительное действие (по умолчанию ПКМ).</summary>
    Secondary,
}
