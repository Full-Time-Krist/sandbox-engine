namespace Shared.Blocks;

/// <summary>
/// Форма блока для отрисовки (поле <c>model</c> в JSON блока). Логике мира форма не нужна — её берёт клиент, как текстуры;
/// столкновения задаёт <see cref="BlockDefinition.IsSolid"/>.
/// </summary>
public enum BlockModel
{
    /// <summary>Полный куб — по умолчанию.</summary>
    Cube,

    /// <summary>
    /// Факел: столбик 2 × 10 × 2 пикселя в центре блока, стоит на полу. Берёт из текстуры столбцы 7–8 и строки 6–15
    /// (бока), верх — строки 7–8 тех же столбцов. Блок с этой формой не может быть непрозрачным: он не закрывает соседей.
    /// </summary>
    Torch,
}
